import type { T } from '../packages';
import { t } from '../packages';

/** Folder written into React Native projects with Onlook's bridge files. */
export const ONLOOK_NATIVE_DIR = 'onlook';
export const ONLOOK_NATIVE_PRELOAD_FILE = `${ONLOOK_NATIVE_DIR}/preload.js`;
export const ONLOOK_NATIVE_BABEL_PLUGIN_FILE = `${ONLOOK_NATIVE_DIR}/babel-plugin-react-native.js`;

/**
 * Relative import specifier from a root `_layout` file to the Onlook preload module,
 * e.g. `src/app/_layout.tsx` -> `../../onlook/preload`.
 */
export function getExpoPreloadImportPath(layoutPath: string): string {
    const depth = layoutPath.replace(/^\.?\//, '').split('/').length - 1;
    return `${'../'.repeat(depth) || './'}${ONLOOK_NATIVE_DIR}/preload`;
}

function isPreloadImport(node: T.Statement): boolean {
    return t.isImportDeclaration(node) && /(^|\/)onlook\/preload(\.js)?$/.test(node.source.value);
}

/**
 * Expo Router has no `<html>`/`<body>` to add a `<Script>` to. Instead, the root `_layout`
 * imports a tiny module that loads the preload script on web, inside the Onlook editor only.
 */
export function injectExpoPreloadImport(ast: T.File, layoutPath: string): T.File {
    const source = getExpoPreloadImportPath(layoutPath);
    const body = ast.program.body;
    const existing = body.filter(isPreloadImport);
    if (existing.length === 1 && (existing[0] as T.ImportDeclaration).source.value === source) {
        return ast;
    }
    ast.program.body = body.filter((node) => !isPreloadImport(node));
    ast.program.body.unshift(t.importDeclaration([], t.stringLiteral(source)));
    return ast;
}

/** Contents of `onlook/preload.js`. A no-op on iOS/Android and outside the Onlook editor. */
export function getExpoPreloadModule(scriptSrc: string): string {
    return `// Generated by Onlook. Loads the Onlook editor bridge in the web preview only.
// It does nothing on iOS, Android, or when the app is not opened inside Onlook.
if (
    typeof window !== 'undefined' &&
    typeof document !== 'undefined' &&
    window.self !== window.top &&
    !document.getElementById('onlook-preload-script')
) {
    const script = document.createElement('script');
    script.id = 'onlook-preload-script';
    script.type = 'module';
    script.src = ${JSON.stringify(scriptSrc)};
    document.head.appendChild(script);
}
`;
}

/**
 * Adds Onlook's babel plugin to a babel config so react-native-web keeps `data-oid` attributes.
 * Returns null when the config already references it or can't be safely edited.
 */
export function addOnlookBabelPlugin(content: string): string | null {
    if (content.includes('babel-plugin-react-native')) return null;
    const pluginRef = `'./${ONLOOK_NATIVE_BABEL_PLUGIN_FILE}'`;
    if (/plugins\s*:\s*\[/.test(content)) {
        return content.replace(/plugins\s*:\s*\[/, (match) => `${match}${pluginRef}, `);
    }
    if (/presets\s*:\s*\[/.test(content)) {
        return content.replace(/(\n(\s*)presets\s*:)/, `\n$2plugins: [${pluginRef}],$1`);
    }
    return null;
}

export const DEFAULT_EXPO_BABEL_CONFIG = `module.exports = function (api) {
    api.cache(true);
    return {
        presets: ['babel-preset-expo'],
        plugins: ['./${ONLOOK_NATIVE_BABEL_PLUGIN_FILE}'],
    };
};
`;

/** Source of `onlook/babel-plugin-react-native.js`, written into Expo projects. */
export const ONLOOK_BABEL_PLUGIN_SOURCE = `/**
 * Onlook × React Native
 *
 * Onlook tags every JSX element with \`data-oid\` (and friends) so the visual editor can map
 * DOM nodes back to source. react-native-web drops unknown props, but it forwards \`dataSet\`
 * to \`data-*\` attributes. This plugin rewrites \`data-*\` props on components into \`dataSet\`,
 * so your source keeps plain \`data-oid\` attributes and the web preview keeps them in the DOM.
 * On iOS and Android \`dataSet\` is ignored, so native builds are unaffected.
 */
module.exports = function onlookReactNative({ types: t }) {
    const toKey = (name) => name.slice('data-'.length).replace(/-([a-z])/g, (_, c) => c.toUpperCase());

    return {
        name: 'onlook-react-native',
        visitor: {
            JSXOpeningElement(path) {
                const { name } = path.node;
                // Host DOM elements (<div>) already keep data-* attributes.
                if (t.isJSXIdentifier(name) && /^[a-z]/.test(name.name)) return;

                const dataAttrs = [];
                let dataSetAttr = null;
                for (const attr of path.node.attributes) {
                    if (!t.isJSXAttribute(attr) || !t.isJSXIdentifier(attr.name)) continue;
                    if (attr.name.name === 'dataSet') dataSetAttr = attr;
                    else if (attr.name.name.startsWith('data-')) dataAttrs.push(attr);
                }
                if (dataAttrs.length === 0) return;

                const properties = dataAttrs.map((attr) => {
                    let value = attr.value ?? t.booleanLiteral(true);
                    if (t.isJSXExpressionContainer(value)) value = value.expression;
                    return t.objectProperty(t.stringLiteral(toKey(attr.name.name)), value);
                });

                path.node.attributes = path.node.attributes.filter((a) => !dataAttrs.includes(a));
                if (dataSetAttr && t.isJSXExpressionContainer(dataSetAttr.value)) {
                    const existing = dataSetAttr.value.expression;
                    dataSetAttr.value.expression = t.isObjectExpression(existing)
                        ? t.objectExpression([...existing.properties, ...properties])
                        : t.objectExpression([t.spreadElement(existing), ...properties]);
                } else {
                    path.node.attributes.push(
                        t.jsxAttribute(
                            t.jsxIdentifier('dataSet'),
                            t.jsxExpressionContainer(t.objectExpression(properties)),
                        ),
                    );
                }
            },
        },
    };
};
`;
